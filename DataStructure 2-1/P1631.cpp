/**
 * Luogu P1631 - 序列合并
 *
 * 问题描述：
 *   给定两个长度为 n 的单调不降序列 A、B。从两个序列中各选一个数相加，
 *   一共可以得到 n^2 个和，要求按从小到大的顺序输出其中最小的 n 个。
 *
 * 解法：单调性剪枝 + 固定容量大根堆
 *   将所有和看成矩阵 M[i][j] = B[i] + A[j]。由于 A 单调不降，固定 B[i]
 *   后，这一行的和也单调不降；B 的单调性则使各行同一列的和单调不降。
 *
 *   使用大根堆 pq 保存当前找到的最小 n 个和。堆顶是这 n 个候选中的最大值，
 *   也就是新候选能否进入答案集合的筛选阈值：
 *   1. 堆未满时，直接将当前和放入堆中；
 *   2. 当前和小于堆顶时，用它替换堆顶；
 *   3. 当前和不小于堆顶时，同一行后面的和只会更大，可以立即停止枚举该行。
 *
 *   第一行会先填满堆。此后每处理完一行，pq 都保存已经处理的各行中最小的
 *   n 个和；按照上述规则扫描下一行后，这一性质仍然成立。
 *
 * 复杂度分析：
 *   对 1-based 的第 i 个 B，若它与第 j 个 A 组成的和能够进入堆，则前 i 个 B
 *   和前 j 个 A 已构成 i*j 个不大于它的和，因此必须有 i*j <= n，即 j <= n/i。
 *   所有行成功进入堆的候选数之和为 O(n/1+n/2+...+n/n)=O(n log n)，每行还
 *   至多进行一次触发 break 的比较。每次堆更新需要 O(log n)：
 *   - 时间复杂度：O(n log^2 n)
 *   - 空间复杂度：O(n)
 */

#include <iostream>
#include <queue>
#include <vector>
using namespace std;

int main() {
    int n;
    cin >> n;
    // a 保存序列 A；得到答案后复用该数组按升序存放最小的 n 个和。
    vector a(n, 0);
    // 大根堆中始终保留当前最小的 n 个候选和，堆顶是其中最大的筛选阈值。
    priority_queue<int> pq;
    for (int i = 0; i < n; i++) cin >> a[i];

    // 按单调不降顺序逐个读入 B[i]，并依次扫描这一行的 A[j] + B[i]。
    for (int i = 0; i < n; i++) {
        int b;
        cin >> b;
        for (int j = 0; j < n; j++) {
            if (pq.size() < n) {
                // 第一行用于填满堆，建立最初的 n 个候选和。
                pq.push(a[j] + b);
            } else if (a[j] + b < pq.top()) {
                // 用更小的和替换当前候选集合中的最大值。
                pq.pop();
                pq.push(a[j] + b);
            } else {
                // A 单调不降，后续的 A[j] + b 也不会小于当前堆顶，无需继续枚举。
                break;
            }
        }
    }

    // 大根堆按从大到小弹出；倒序写入 a 后即可得到升序答案。
    for (int i = 0; i < n; i++) {
        a[n - i - 1] = pq.top();
        pq.pop();
    }

    for (int num: a) cout << num << ' ';
    return 0;
}
