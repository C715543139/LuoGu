/**
 * Luogu P1613 - 跑路
 *
 * 问题描述：
 *   给定一个有向图，每条边长度为 1 千米。每秒可以选择跑路 2^k 千米，
 *   求从节点 1 到节点 n 所需的最少秒数。
 *
 * 解法：二进制长度倍增 + Floyd 动态规划
 *   一次跑路覆盖的路程必须是 2 的幂，因此可以先求出任意两个节点之间
 *   是否存在长度为 2^k 的路径，再把这些路径看成“花费 1 秒”的新边。
 *
 *   path[k][i][j] 表示是否存在一条从 i 到 j、长度恰好为 2^k 的路径。
 *   初始时每条原边都是长度为 1=2^0 的路径。若存在两条长度为 2^(k-1)
 *   的路径 i->mid 和 mid->j，就可以拼成一条长度为 2^k 的路径 i->j。
 *   图中允许重复经过节点，所以这种拼接也能正确处理环和重复边。
 *
 *   dp[i][j] 表示目前已知从 i 到 j 所需的最少秒数。每条长度为 2^k 的
 *   路径都可以在 1 秒内完成，因此将对应的 dp[i][j] 更新为 1。
 *   任意正整数路程都可以拆成若干个互不重复的二进制位对应的 2 的幂，
 *   所以在这些新边上求最短路，就等价于求最少秒数。最后使用 Floyd 枚举
 *   中间节点，完成 dp[i][j] = min(dp[i][j], dp[i][mid] + dp[mid][j])。
 *
 * 复杂度分析：
 *   - 时间复杂度：O(32n^3+n^3)，倍增建边和 Floyd 各进行常数层的三重循环；
 *   - 空间复杂度：O(32n^2)，用于保存所有长度层的可达性和最短时间。
 */

#include <iostream>
#include <vector>
#include <climits>
using namespace std;

int main() {
    // 读入节点数和有向边数
    int n, m;
    cin >> n >> m;

    // dp[i][j] 保存从 i 到 j 的最少跑路秒数，初始视为不可达
    vector dp(n + 1, vector(n + 1, INT_MAX / 3));

    // path[k][i][j] 表示是否存在一条 i 到 j、长度为 2^k 的路径
    vector path(32, vector(n + 1, vector(n + 1, false)));

    // 原图中的每条边长度为 1=2^0，可以在 1 秒内完成
    for (int i = 0; i < m; i++) {
        int u, v;
        cin >> u >> v;
        path[0][u][v] = true;
        dp[u][v] = 1;
    }

    // 通过拼接两条相同长度的路径，递推出长度为 2^t 的路径
    for (int t = 1; t < 32; t++) {
        // k 作为两段路径的连接点
        for (int k = 1; k <= n; k++) {
            for (int i = 1; i <= n; i++) {
                for (int j = 1; j <= n; j++) {
                    if (path[t - 1][i][k] && path[t - 1][k][j]) {
                        // i->k 和 k->j 各长 2^(t-1)，合并后长度为 2^t
                        path[t][i][j] = true;

                        // 整条长度为 2^t 的路径可以一次跑路完成
                        dp[i][j] = 1;
                    }
                }
            }
        }
    }

    // 在所有“1 秒可走完”的新边上求最少边数，即最少跑路秒数
    for (int k = 1; k <= n; k++) {
        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= n; j++) {
                // 枚举经过中间节点 k 的方案
                dp[i][j] = min(dp[i][j], dp[i][k] + dp[k][j]);
            }
        }
    }

    cout << dp[1][n] << endl;
    return 0;
}
