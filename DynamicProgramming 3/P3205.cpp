/**
 * Luogu P3205 - [HNOI2010] 合唱队
 *
 * 问题描述：
 *   给定一个最终队形。按照指定规则依次加入每个人：
 *   如果新加入的人比前一个加入的人高，就放在当前队形的最右边；
 *   如果新加入的人比前一个加入的人矮，就放在当前队形的最左边。
 *   求能够得到给定最终队形的初始排列数量。
 *
 * 解法：区间动态规划
 *   由于每次新加入的人只能放在当前队形的左端或右端，
 *   所以已经加入的人在最终队形中一定构成一个连续区间 [l, r]。
 *   下一次加入的人只能是区间左侧的 h[l-1] 或右侧的 h[r+1]。
 *
 *   设 dp[l][r][0] 表示当前已经加入最终队形中的 h[l] 到 h[r]，
 *   且最后加入的人是 h[l] 时的初始排列数量；
 *   设 dp[l][r][1] 表示当前已经加入 h[l] 到 h[r]，
 *   且最后加入的人是 h[r] 时的初始排列数量。
 *
 *   计算 dp[l][r][0] 时，最后加入的人是左端 h[l]，
 *   所以之前已经加入的区间一定是 [l+1, r]。
 *   h[l] 要被放在左端，必须比之前最后加入的人矮：
 *     - 之前最后加入 h[l+1]：需要 h[l] < h[l+1]；
 *     - 之前最后加入 h[r]：需要 h[l] < h[r]。
 *
 *   计算 dp[l][r][1] 时，最后加入的人是右端 h[r]，
 *   所以之前已经加入的区间一定是 [l, r-1]。
 *   h[r] 要被放在右端，必须比之前最后加入的人高：
 *     - 之前最后加入 h[l]：需要 h[r] > h[l]；
 *     - 之前最后加入 h[r-1]：需要 h[r] > h[r-1]。
 *
 *   区间只有一个人时，这个人可以作为初始队形中的第一个人，
 *   因此设置 dp[i][i][0] = 1。为避免同一个初始排列被重复计算，
 *   将 dp[i][i][1] 设置为 0。
 *
 * 复杂度分析：
 *   - 时间复杂度：O(n^2)，枚举区间左端点和右端点；
 *   - 空间复杂度：O(n^2)。
 */

#include <iostream>
#include <vector>
using namespace std;

int main() {
    // 读入合唱队人数
    int n;
    cin >> n;

    // h[i] 表示最终队形中第 i 个人的身高，下标从 1 开始
    vector h(n + 1, 0);
    for (int i = 1; i <= n; i++) {
        cin >> h[i];
    }

    // dp[l][r][0/1] 分别表示最后加入的人位于区间左端/右端时的方案数
    vector dp(n + 1, vector(n + 1, vector(2, 0)));

    // 只有一个人时，他可以作为初始队形中的第一个人
    // 只保留左端状态，避免同一个排列被左右端状态重复统计
    for (int i = 0; i <= n; i++) {
        dp[i][i][0] = 1;
        dp[i][i][1] = 0;
    }

    // 按区间长度从小到大计算，保证转移所需的区间已经求出
    for (int len = 2; len <= n; len++) {
        for (int l = 1; l + len - 1 <= n; l++) {
            int r = l + len - 1;

            // 最后加入左端 h[l]，之前的区间为 [l+1, r]
            // 若之前最后加入 h[l+1]，h[l] 必须比 h[l+1] 矮，才能放到左端
            if (h[l] < h[l + 1]) {
                dp[l][r][0] += dp[l + 1][r][0];
            }

            // 若之前最后加入 h[r]，h[l] 必须比 h[r] 矮，才能放到左端
            if (h[l] < h[r]) {
                dp[l][r][0] += dp[l + 1][r][1];
            }

            // 最后加入右端 h[r]，之前的区间为 [l, r-1]
            // 若之前最后加入 h[l]，h[r] 必须比 h[l] 高，才能放到右端
            if (h[r] > h[l]) {
                dp[l][r][1] += dp[l][r - 1][0];
            }

            // 若之前最后加入 h[r-1]，h[r] 必须比 h[r-1] 高，才能放到右端
            if (h[r] > h[r - 1]) {
                dp[l][r][1] += dp[l][r - 1][1];
            }

            // 方案数较大，按照题目要求对指定模数取模
            dp[l][r][0] %= 19650827;
            dp[l][r][1] %= 19650827;
        }
    }

    // 所有人都加入后，最后加入的人可能位于最终队形的左端或右端
    cout << (dp[1][n][0] + dp[1][n][1]) % 19650827 << endl;
    return 0;
}
