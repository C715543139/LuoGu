/**
 * Luogu P1435 - [IOI 2000] 回文字串
 *
 * 问题描述：
 *   给定一个字符串，求至少插入多少个字符后可以将它变成回文串。
 *
 * 解法：最长公共子序列
 *   设原字符串为 s，逆序字符串为 reverse(s)。
 *   原字符串的最长回文子序列，等于 s 与 reverse(s) 的最长公共子序列。
 *
 *   保留最长回文子序列中的字符，不需要插入字符；
 *   对于其余字符，可以通过插入对应字符的方式补成回文串。
 *   因此，最少插入字符数为：
 *     字符串长度 - 最长回文子序列长度。
 *
 *   设 dp[i][j] 表示原字符串前 i 个字符与逆序字符串前 j 个字符的最长公共子序列长度。
 *   当两个当前字符相等时，可以将它们加入公共子序列；
 *   当两个当前字符不相等时，可以舍弃其中一个字符，取两种情况的较大值。
 *
 *   代码中没有单独创建逆序字符串，而是通过 s[size - j] 直接访问逆序字符串的第 j 个字符。
 *
 * 复杂度分析：
 *   - 时间复杂度：O(l^2)，其中 l 为字符串长度；
 *   - 空间复杂度：O(l^2)。
 */

#include <iostream>
#include <vector>
using namespace std;

int main() {
    // 读入字符串
    string s;
    cin >> s;

    // size 表示字符串长度
    int size = s.size();

    // dp[i][j] 表示 s 的前 i 个字符与逆序字符串的前 j 个字符的最长公共子序列长度
    vector dp(size + 1, vector(size + 1, 0));

    // 枚举两个字符串的前缀长度
    for (int i = 1; i <= size; ++i) {
        for (int j = 1; j <= size; ++j) {
            // s[i-1] 是原字符串的第 i 个字符
            // s[size-j] 是逆序字符串的第 j 个字符
            // 不论当前字符是否相等，都可以跳过原字符串或逆序字符串中的一个字符
            dp[i][j] = max(max(dp[i - 1][j], dp[i][j - 1]), dp[i - 1][j - 1] + (s[i - 1] == s[size - j]));
        }
    }

    // 最少插入字符数 = 字符串长度 - 最长回文子序列长度
    cout << size - dp[size][size] << endl;
    return 0;
}
