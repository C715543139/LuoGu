/**
 * Luogu P1140 - [ICPC 2001 Taejon R] 相似基因
 *
 * 问题描述：
 *   给定两个只包含 A、C、G、T 的基因序列，允许在序列中插入空碱基 '-'，
 *   使两个序列可以逐列对应。每一列根据两个碱基的组合获得相应分数，
 *   求所有合法对应方式中的最大相似度。
 *
 * 解法：序列比对动态规划
 *   设 dp[i][j] 表示 s1 的前 i 个字符和 s2 的前 j 个字符进行对应时的最大相似度。
 *
 *   考虑最后一列的对应方式，共有三种情况：
 *   1. s1[i-1] 与 s2[j-1] 对应，转移自 dp[i-1][j-1]；
 *   2. s1[i-1] 与空碱基 '-' 对应，转移自 dp[i-1][j]；
 *   3. 空碱基 '-' 与 s2[j-1] 对应，转移自 dp[i][j-1]。
 *
 *   因此状态转移方程为：
 *     dp[i][j] = max(
 *         dp[i-1][j-1] + val[s1[i-1]][s2[j-1]],
 *         dp[i-1][j] + val[s1[i-1]]['-'],
 *         dp[i][j-1] + val['-'][s2[j-1]]
 *     )。
 *
 *   当其中一个序列为空时，另一个序列中的所有字符都只能与空碱基对应，
 *   因此需要单独初始化 dp[i][0] 和 dp[0][j]。
 *
 * 复杂度分析：
 *   - 时间复杂度：O(l1 * l2)，每个状态只需要比较三种转移；
 *   - 空间复杂度：O(l1 * l2)。
 */

#include <iostream>
#include <unordered_map>
#include <vector>
using namespace std;

int main() {
    // 读入两个基因序列的长度和序列内容
    int l1, l2;
    string s1, s2;
    cin >> l1 >> s1 >> l2 >> s2;

    // 将碱基字符转换为相似度表中的行号或列号
    // A、C、G、T 对应 0、1、2、3，空碱基 '-' 对应 4
    auto trans = [](const char c) {
        switch (c) {
            case 'A':
                return 0;
            case 'C':
                return 1;
            case 'G':
                return 2;
            case 'T':
                return 3;
            default:
                return -1;
        }
    };

    // val[i][j] 表示第 i 种碱基和第 j 种碱基对应时的相似度
    // 第 5 行和第 5 列表示空碱基 '-'
    // val[4][4] 不会被使用，因为两个空碱基不能互相对应
    vector<vector<int>> val = {
        {5, -1, -2, -1, -3},
        {-1, 5, -3, -2, -4},
        {-2, -3, 5, -2, -2},
        {-1, -2, -2, 5, -1},
        {-3, -4, -2, -1, 65535}
    }, dp(l1 + 1, vector(l2 + 1, 0));

    // 初始化 s2 为空的情况：s1 中的每个字符都与空碱基对应
    for (int i = 1; i <= l1; ++i) {
        dp[i][0] = dp[i - 1][0] + val[trans(s1[i - 1])][4];
    }

    // 初始化 s1 为空的情况：s2 中的每个字符都与空碱基对应
    for (int j = 1; j <= l2; ++j) {
        dp[0][j] = dp[0][j - 1] + val[trans(s2[j - 1])][4];
    }

    // 枚举两个基因序列的前缀长度
    for (int i = 1; i <= l1; ++i) {
        for (int j = 1; j <= l2; ++j) {
            // t1 和 t2 分别表示当前两个碱基在相似度表中的下标
            int t1 = trans(s1[i - 1]), t2 = trans(s2[j - 1]);

            // 枚举最后一列的三种对应方式，并取相似度最大的方案
            dp[i][j] = max(dp[i - 1][j - 1] + val[t1][t2],
                           max(dp[i][j - 1] + val[t2][4], dp[i - 1][j] + val[t1][4]));
        }
    }

    // 输出两个完整基因序列的最大相似度
    cout << dp[l1][l2] << endl;
    return 0;
}
