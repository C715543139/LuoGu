/**
 * Luogu P2834 - 纸币问题 3
 *
 * 问题描述：
 *   有 n 种面额互不相同、数量无限的纸币，求恰好支付金额 w 的纸币组合数。相同的
 *   纸币组合不因支付顺序不同而重复计数，答案对 10^9+7 取模。
 *
 * 解法：完全背包计数 DP
 *   dp[i] 表示已经处理过的纸币能够凑出金额 i 的组合数。初始时 dp[0]=1，表示
 *   不选择任何纸币恰好凑出 0 元的一种方案。
 *
 *   枚举当前面额 a 时，从小到大更新每个金额 i：
 *       dp[i] = dp[i] + dp[i-a]
 *   更新前的 dp[i] 表示不使用 a 的组合；此时 dp[i-a] 已经完成当前面额 a 的更新，
 *   表示先支付一张 a 元纸币后剩余金额的组合。金额从小到大枚举，使 a 能被重复使用。
 *   纸币面额在外层枚举，每种组合只会按面额的固定处理顺序构造一次。
 *
 * 复杂度分析：
 *   - 时间复杂度：O(nw)
 *   - 空间复杂度：O(w)
 */

#include <iostream>
#include <vector>
using namespace std;

int main() {
    int n, w;
    cin >> n >> w;
    // v 保存 n 种纸币面额；dp[i] 保存当前已处理面额凑出 i 元的组合数。
    vector v(n, 0), dp(w + 1, 0);
    for (int i = 0; i < n; i++) {
        cin >> v[i];
    }

    // 空组合构成凑出 0 元的唯一方案，是后续转移的起点。
    dp[0] = 1;
    for (int a: v) {
        // 固定当前面额 a，避免同一组合因纸币排列不同被重复计数。
        for (int i = a; i <= w; i++) {
            // dp[i-a] 已包含当前面额 a 的贡献，因此一张 a 可以被无限次使用。
            dp[i] = (dp[i - a] + dp[i]) % 1000000007;
        }
    }
    // 所有面额处理完成后，dp[w] 即为支付 w 元的组合数。
    cout << dp[w] << endl;
    return 0;
}
