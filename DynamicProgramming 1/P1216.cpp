/**
 * Luogu P1216 - [IOI 1994 / USACO1.5] 数字三角形
 *
 * 问题描述：
 *   从数字三角形顶端出发，每一步只能走向左下或右下相邻数字，求到达最底层时经过
 *   数字之和的最大值。
 *
 * 解法：自底向上的动态规划
 *   将 v[i][j] 更新为从位置 (i,j) 出发走到底层所能得到的最大路径和。最底层不再
 *   向下转移，初始值就是它本身；其余位置只能走向下一行的 (i+1,j) 或 (i+1,j+1)，
 *   因此：
 *       v[i][j] = v[i][j] + max(v[i+1][j], v[i+1][j+1])
 *   从倒数第二行向上更新后，v[0][0] 即为从顶端到底层的最大路径和。
 *
 * 复杂度分析：
 *   三角形共有 r(r+1)/2 个数字，每个数字只处理一次：
 *   - 时间复杂度：O(r^2)
 *   - 空间复杂度：O(r^2)
 */

#include <iostream>
#include <vector>
using namespace std;

int main() {
    int r;
    cin >> r;
    // v[i] 保存第 i 行的所有数字，第 i 行共有 i+1 个位置。
    vector<vector<int>> v(r);
    for (int i = 0; i < r; ++i) {
        v[i].assign(i + 1, 0);
        for (int j = 0; j <= i; ++j) {
            cin >> v[i][j];
        }
    }
    // 自底向上更新，使 v[i][j] 表示从该位置出发到底层的最大路径和。
    for (int i = r - 2; i >= 0; --i) {
        for (int j = 0; j <= i; ++j) {
            // 下一步只能走到左下或右下位置，选择两条后续路径中更大的结果。
            v[i][j] += max(v[i + 1][j], v[i + 1][j + 1]);
        }
    }
    // 顶点对应的最大路径和就是整个三角形的答案。
    cout << v[0][0] << endl;
    return 0;
}
