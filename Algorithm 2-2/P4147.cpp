/**
 * Luogu P4147 - 玉蟾宫
 *
 * 问题描述：
 *   在由 F 和 R 组成的 n×m 网格中，求一个全部由 F 构成的最大矩形面积 S，
 *   输出 3×S。
 *
 * 解法：悬线法（逐行维护最大矩形边界）
 *   1. up[j] 表示第 j 列从当前行向上连续 F 的数量，即矩形可用高度。
 *   2. l[j]、r[j] 表示以当前行为底边、经过第 j 列的全 F 矩形的左右边界。
 *      左边界取历史边界与当前行最近左侧 R 的右侧中较大者；
 *      右边界取历史边界与当前行最近右侧 R 的左侧中较小者。
 *   3. 遇到 R 时，将该列高度清零并重置边界；这样任何包含 R 的矩形都会失效。
 *   4. 每行扫描完成后，up[j] × (r[j]-l[j]+1) 即为以该列为悬线的候选面积。
 *
 * 复杂度分析：
 *   - 时间复杂度：O(nm)，每行从左、从右各扫描一次
 *   - 空间复杂度：O(nm)，当前实现保存整个网格；边界状态额外占 O(m)
 */

#include <iostream>
#include <vector>
using namespace std;

int main() {
    int n, m;
    cin >> n >> m;

    // v[i][j]=true 表示格子 (i,j) 为 F，false 表示为 R；下标从 1 开始
    vector v(n + 1, vector(m + 1, false));
    // 读入土地类型
    for (int i = 1; i <= n; ++i) {
        for (int j = 1; j <= m; ++j) {
            char c;
            cin >> c;
            v[i][j] = c == 'F';
        }
    }

    // s：目前找到的最大全 F 矩形面积
    int s = 0;
    // l[j]、r[j]：当前行下，第 j 列所在可行矩形的左右边界（均为闭区间）
    // up[j]：第 j 列从当前行向上连续 F 的高度
    vector r(m + 1, m), l(m + 1, 1), up(m + 1, 0);
    // 逐行将当前行视为候选矩形的底边
    for (int i = 1; i <= n; ++i) {
        // lastR：当前行中已扫描部分最右侧 R 的列号
        // nextR：当前行中已扫描部分最左侧 R 的列号（从右向左扫描时维护）
        int lastR = 0, nextR = m + 1;
        for (int j = 1; j <= m; ++j) {
            if (v[i][j]) {
                // 当前格为 F：高度增加，左边界需同时满足历史行与当前行的限制
                l[j] = max(l[j], lastR + 1);
                up[j]++;
            } else {
                // 当前格为 R：连续 F 高度中断，下一行从新的边界状态开始
                l[j] = 1;
                r[j] = m;
                up[j] = 0;
                lastR = j;
            }

            // 同时从右向左处理第 k 列，维护其右边界
            int k = m - j + 1;
            if (v[i][k]) {
                // 当前格为 F：右边界需同时满足历史行与当前行的限制
                r[k] = min(r[k], nextR - 1);
            } else {
                // 当前格为 R：它成为左侧格子的最近右侧障碍
                nextR = k;
            }
        }
        // 枚举每列作为悬线，计算以当前行为底边的最大候选矩形
        for (int j = 1; j <= m; ++j) {
            s = max(s, up[j] * (r[j] - l[j] + 1));
        }
    }
    // 每单位面积可获得 3 两银子
    cout << 3 * s << endl;
    return 0;
}
