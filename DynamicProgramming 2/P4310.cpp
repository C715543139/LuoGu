/**
 * Luogu P4310 - 绝世好题
 *
 * 问题描述：
 *   给定一个数列，求其中满足相邻元素按位与不为 0 的最长子序列长度。
 *   子序列中的元素不需要连续，但必须保持原数列中的相对顺序。
 *
 * 解法：动态规划
 *   对于已经处理过的元素，使用集合 st 保存若干个状态：
 *   - first：当前子序列的长度；
 *   - second：当前子序列的最后一个元素。
 *
 *   集合按照子序列长度从大到小排列。处理新元素 v[i] 时，
 *   从最长的已有子序列开始查找：如果该子序列的末尾元素与 v[i] 的按位与不为 0，
 *   就将 v[i] 接到该子序列后面，并记录新的长度。
 *   如果没有找到可以连接的状态，则将 v[i] 单独作为后续转移使用的长度为 1 的状态。
 *
 *   两个数的按位与不为 0，说明它们至少有一个二进制位同时为 1，
 *   因而满足题目要求的相邻条件。
 *
 * 复杂度分析：
 *   - 时间复杂度：最坏为 O(n^2)，因为每次处理元素时可能遍历集合中的所有状态；
 *   - 空间复杂度：O(n)，集合中最多保存每个元素对应的一个状态。
 */

#include <iostream>
#include <set>
#include <vector>
using namespace std;

int main() {
    // 读入数列长度和数列中的元素
    int n;
    cin >> n;
    vector v(n, 0);
    for (int i = 0; i < n; i++) {
        cin >> v[i];
    }

    // res 保存目前找到的最长合法子序列长度
    int res = 0;

    // 按子序列长度从大到小保存状态
    // 每个状态表示：子序列长度，以及该子序列的最后一个元素
    set<pair<int, int>, greater<>> st;

    // 单个元素只能作为后续转移的基础状态，不能计入最终答案
    st.insert({1, v[0]});

    // 依次处理后续元素，保证选出的子序列符合原数列顺序
    for (int i = 1; i < n;) {
        // 优先尝试连接长度最长的已有子序列
        for (auto [k, val]: st) {
            // 按位与不为 0，说明当前元素可以接在该子序列后面
            if ((val & v[i]) != 0) {
                res = max(res, k + 1);
                st.insert({k + 1, v[i]});

                // 当前元素已经找到可连接的最长状态，结束本轮查找
                goto out;
            }
        }

        // 当前元素无法连接任何已有状态，只能作为新序列的起点
        st.insert({1, v[i]});
    out:
        // 处理下一个元素
        i++;
    }

    // 输出最长合法子序列长度
    cout << res << endl;
    return 0;
}
