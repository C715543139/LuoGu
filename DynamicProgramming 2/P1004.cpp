/**
 * Luogu P1004 - [NOIP 2000 提高组] 方格取数
 *
 * 问题描述：
 *   两个人从方格左上角出发，只能向右或向下走到右下角。
 *   经过一个格子时可以取走其中的数字，同一个格子的数字只能被取走一次。
 *   求两条路径能够取得的最大数字总和。
 *
 * 解法：四维动态规划
 *   让两个人同时从左上角出发，并且每次各走一步。
 *   设 dp[x1][y1][x2][y2] 表示：
 *   - 第一个人位于 (x1, y1)；
 *   - 第二个人位于 (x2, y2)；
 *   - 两个人同时走到这两个位置时能够取得的最大数字总和。
 *
 *   两个人每次都只能向右或向下走，因此每个状态有四种转移来源：
 *   1. 两个人都从上方走来；
 *   2. 第一个人从左方走来，第二个人从上方走来；
 *   3. 第一个人从上方走来，第二个人从左方走来；
 *   4. 两个人都从左方走来。
 *
 *   两个人同步行走，所以到达 (x1, y1) 和 (x2, y2) 时，
 *   必须满足两人走过的步数相同：
 *     x1 + y1 = x2 + y2
 *
 *   如果两个人位于不同格子，则将两个格子的数字都加入答案；
 *   如果两个人位于同一个格子，则该格子的数字只能计算一次。
 *
 * 复杂度分析：
 *   - 时间复杂度：O(N^4)；
 *   - 空间复杂度：O(N^4)。
 *   由于 N <= 9，四维状态可以满足题目要求。
 */

#include <algorithm>
#include <iostream>
#include <vector>
using namespace std;

int main() {
    // 读入棋盘大小
    int n;
    cin >> n;

    // points[i][j] 表示第 i 行第 j 列格子中的数字
    vector points(n + 1, vector<int>(n + 1, 0));

    // 题目给出的坐标从 1 开始，因此数组也使用 1-based 下标
    int x, y, value;
    while (cin >> x >> y >> value && (x != 0 || y != 0 || value != 0)) {
        points[x][y] = value;
    }

    // dp[x1][y1][x2][y2] 表示两个人分别位于两个位置时的最大得分
    vector dp(
        n + 1,
        vector(n + 1,
               vector(n + 1,
                      vector<int>(n + 1, 0)))
    );

    // 两个人都从左上角出发，起点数字只计算一次
    dp[1][1][1][1] = points[1][1];

    // 按两个人的位置从左上到右下依次计算状态
    for (int x1 = 1; x1 <= n; ++x1) {
        for (int y1 = 1; y1 <= n; ++y1) {
            for (int x2 = 1; x2 <= n; ++x2) {
                for (int y2 = 1; y2 <= n; ++y2) {
                    // 两个人必须同步行走，经过的步数必须相同
                    if (x1 + y1 != x2 + y2) {
                        continue;
                    }

                    // 起点已经初始化，不需要再次从前驱状态转移
                    if (x1 == 1 && y1 == 1 && x2 == 1 && y2 == 1) {
                        continue;
                    }

                    // 当前状态的四种可能前驱
                    int best = 0;

                    // 两个人都从上方走来
                    if (x1 > 1 && x2 > 1) {
                        best = max(best, dp[x1 - 1][y1][x2 - 1][y2]);
                    }

                    // 第一个人从左方走来，第二个人从上方走来
                    if (y1 > 1 && x2 > 1) {
                        best = max(best, dp[x1][y1 - 1][x2 - 1][y2]);
                    }

                    // 第一个人从上方走来，第二个人从左方走来
                    if (x1 > 1 && y2 > 1) {
                        best = max(best, dp[x1 - 1][y1][x2][y2 - 1]);
                    }

                    // 两个人都从左方走来
                    if (y1 > 1 && y2 > 1) {
                        best = max(best, dp[x1][y1 - 1][x2][y2 - 1]);
                    }

                    // 两个人位于同一个格子时，该格子的数字只能计算一次
                    if (x1 == x2 && y1 == y2) {
                        dp[x1][y1][x2][y2] = best + points[x1][y1];
                    } else {
                        // 两个人位于不同格子，可以分别取得两个格子的数字
                        dp[x1][y1][x2][y2] = best + points[x1][y1] + points[x2][y2];
                    }
                }
            }
        }
    }

    // 两个人最终都到达右下角，输出最大得分
    cout << dp[n][n][n][n] << '\n';
    return 0;
}
