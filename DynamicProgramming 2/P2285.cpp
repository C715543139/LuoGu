/**
 * Luogu P2285 - [HNOI2004] 打鼹鼠
 *
 * 问题描述：
 *   在 n×n 的网格中，鼹鼠会在指定时刻出现在指定位置。机器人每个时刻最多移动一格，
 *   也可以停留在原地；当机器人与鼹鼠处于同一网格时，可以打死这只鼹鼠。求机器人在
 *   整段时间内最多能打死多少只鼹鼠。游戏开始时，机器人可以自由选择初始位置。
 *
 * 解法：最长可行序列上的动态规划
 *   机器人从位置 (x_1, y_1) 移动到位置 (x_2, y_2)，至少需要经过：
 *       |x_1-x_2| + |y_1-y_2|
 *   个时刻，这个距离称为两点之间的曼哈顿距离。若第 j 只鼹鼠被打死后，经过足够的时间
 *   能到达第 i 只鼹鼠的位置，则可以按 j -> i 的顺序连续打死它们。
 *
 *   设 dp[i] 表示以第 i 只鼹鼠作为最后一只被打死的鼹鼠时，最多能打死的鼹鼠数量。
 *   由于机器人可以自由选择初始位置，每只鼹鼠都可以作为第一只被打死的鼹鼠，因此初值为：
 *       dp[i] = 1
 *   若 j < i 且满足：
 *       t_i-t_j >= |x_i-x_j| + |y_i-y_j|
 *   则机器人可以从第 j 只鼹鼠的位置赶到第 i 只鼹鼠的位置，状态转移为：
 *       dp[i] = max(dp[i], dp[j]+1)
 *   最终答案为所有 dp[i] 中的最大值。由于鼹鼠出现时间按不降顺序给出，只需从前往后
 *   枚举每只鼹鼠，并检查它之前的所有鼹鼠即可。
 *
 * 复杂度分析：
 *   - 时间复杂度：O(m^2)，每只鼹鼠都枚举其之前的所有鼹鼠
 *   - 空间复杂度：O(m)，保存所有鼹鼠的信息和动态规划状态
 */

#include <iostream>
#include <vector>
using namespace std;

int main() {
    int n, m;
    cin >> n >> m;

    // it 保存一只鼹鼠出现的时刻和所在位置；n 只用于描述网格大小，转移时无需使用。
    class it {
    public:
        int t, x, y;
        it(int t, int x, int y) : t(t), x(x), y(y) {}
    };

    // 下标从 1 开始，方便按照输入顺序表示第 1 到第 m 只鼹鼠。
    vector<it> v(m + 1, {0, 0, 0});
    for (int i = 1; i <= m; ++i) {
        cin >> v[i].t >> v[i].x >> v[i].y;
    }

    // res 保存目前为止能够打死的最多鼹鼠数量。
    int res = 0;
    // dp[i] 表示以第 i 只鼹鼠作为最后目标时，最多能打死的鼹鼠数量。
    vector dp(m + 1, 1);
    for (int i = 1; i <= m; ++i) {
        // 枚举第 i 只鼹鼠之前的最后一只鼹鼠 j，尝试将第 i 只接在其后。
        for (int j = 1; j < i; ++j) {
            // 两只鼹鼠之间的时间差至少要达到曼哈顿距离，机器人才能按顺序到达。
            if (dp[i] < dp[j] + 1
                && (v[i].t - v[j].t) >= abs(v[i].x - v[j].x) + abs(v[i].y - v[j].y)) {
                // 可以从第 j 只鼹鼠移动到第 i 只鼹鼠，更新以 i 结尾的最优值。
                dp[i] = dp[j] + 1;
            }
        }
        // 第 i 只鼹鼠也可以作为第一只目标，dp[i] 至少为 1。
        res = max(res, dp[i]);
    }

    // 输出能够打死的鼹鼠最大数量。
    cout << res << endl;
    return 0;
}
