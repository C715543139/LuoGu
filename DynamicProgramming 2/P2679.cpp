/**
 * Luogu P2679 - [NOIP 2015 提高组] 子串
 *
 * 问题描述：
 *   从字符串 A 中选出 k 个互不重叠的非空子串，并按照它们在 A 中的出现顺序连接，
 *   使连接后的字符串恰好等于 B，求满足条件的方案数。
 *
 * 解法：动态规划
 *   设 dp[i][j][l][0/1] 表示使用 A 的前 i 个字符，匹配 B 的前 j 个字符，
 *   选出了 l 个子串时的方案数：
 *   - 状态 0：A 的第 i 个字符没有被选入当前方案；
 *   - 状态 1：A 的第 i 个字符被选入当前方案。
 *
 *   当 A 的第 i 个字符没有被选中时，可以直接跳过它：
 *     dp[i][j][l][0] = dp[i-1][j][l][0] + dp[i-1][j][l][1]
 *
 *   当 A[i] 与 B[j] 相等，并且选中 A[i] 时，有三种转移：
 *   1. 从状态 1、子串数量不变转移，表示继续当前子串；
 *   2. 从状态 0、子串数量加一转移，表示从当前字符开始一个新子串；
 *   3. 从状态 1、子串数量加一转移，表示前一个子串在上一个字符结束，
 *      当前字符开始新的子串。
 *
 *   第一维 i 只会从 i-1 转移，因此使用大小为 2 的滚动数组压缩空间。
 *   空字符串可以匹配空字符串，且不需要选择子串，因此初始化 dp[0][0][0][0] = 1。
 *
 * 复杂度分析：
 *   - 时间复杂度：O(nmk)
 *   - 空间复杂度：O(mk)
 */

#include <iostream>
#include <vector>
using namespace std;

int main() {
    // 读入字符串长度、需要匹配的子串数量和两个字符串
    int n, m, k;
    cin >> n >> m >> k;
    string a, b;
    cin >> a >> b;

    // 题目要求对 1e9 + 7 取模
    int mod = 1000000007;

    // 只保留 i-1 和 i 两层，最后一维表示 A 的当前字符是否被选中
    vector dp(2, vector(m + 1, vector(k + 1, vector(2, 0))));

    // 不使用任何字符时，空串匹配空串，且选择了 0 个子串
    dp[0][0][0][0] = 1;

    // 依次考虑字符串 A 的每个字符
    for (int i = 1; i <= n; ++i) {
        // 当前层的 j=0、l=0 表示没有匹配 B，也没有选择子串
        dp[(i - 1) % 2][0][0][0] = 1;

        // 枚举已经匹配的 B 的前缀长度
        for (int j = 1; j <= m; ++j) {
            // 枚举已经选择的子串数量
            for (int l = 1; l <= k; ++l) {
                // 不选择 A[i-1]，当前方案的子串状态保持不变
                dp[i % 2][j][l][0] = (dp[(i - 1) % 2][j][l][0] % mod + dp[(i - 1) % 2][j][l][1] % mod) % mod;

                // 只有当前字符相等时，才能将 A[i-1] 匹配到 B[j-1]
                if (a[i - 1] == b[j - 1]) {
                    // 继续当前子串，或结束前一个子串并从当前字符开始新子串
                    dp[i % 2][j][l][1] =
                    ((dp[(i - 1) % 2][j - 1][l][1] % mod + dp[(i - 1) % 2][j - 1][l - 1][0] % mod) % mod
                     + dp[(i - 1) % 2][j - 1][l - 1][1] % mod) % mod;
                } else {
                    // 字符不匹配，不能选择 A[i-1]，因此该状态不存在
                    dp[i % 2][j][l][1] = 0;
                }
            }
        }
    }

    // 最后一个字符可以未被选中，也可以属于最后一个选出的子串
    cout << (dp[n % 2][m][k][0] + dp[n % 2][m][k][1]) % mod << endl;
    return 0;
}
