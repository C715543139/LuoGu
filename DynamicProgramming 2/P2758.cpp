/**
 * Luogu P2758 - 编辑距离
 *
 * 问题描述：
 *   给定两个字符串 A 和 B，通过删除、插入或修改字符，将 A 转换为 B，
 *   求所需的最少字符操作次数。
 *
 * 解法：动态规划
 *   设 dp[i][j] 表示将字符串 A 的前 i 个字符转换为字符串 B 的前 j 个字符，
 *   所需的最少操作次数。
 *
 *   对于 A 的第 i 个字符和 B 的第 j 个字符，最后一步操作有三种可能：
 *   1. 保留或修改字符：将 A 的前 i-1 个字符转换为 B 的前 j-1 个字符，
 *      如果两个当前字符不同，则额外需要一次修改操作；
 *   2. 插入字符：先将 A 的前 i 个字符转换为 B 的前 j-1 个字符，
 *      再插入 B 的第 j 个字符；
 *   3. 删除字符：先将 A 的前 i-1 个字符转换为 B 的前 j 个字符，
 *      再删除 A 的第 i 个字符。
 *
 *   取以上三种操作的最小值，即可得到 dp[i][j]。
 *   当其中一个字符串为空时，只能通过连续插入或删除完成转换。
 *
 * 复杂度分析：
 *   - 时间复杂度：O(|A| * |B|)
 *   - 空间复杂度：O(|A| * |B|)
 */

#include <iostream>
#include <vector>
using namespace std;

int main() {
    // 读入两个待比较的字符串
    string a, b;
    cin >> a >> b;

    // dp[i][j] 表示 A 的前 i 个字符转换为 B 的前 j 个字符的最少操作次数
    vector dp(a.size() + 1, vector(b.size() + 1, 20000));

    // 将 A 的前 i 个字符转换为空串，只能删除 i 个字符
    for (int i = 0; i <= a.size(); ++i) {
        dp[i][0] = i;
    }

    // 将空串转换为 B 的前 i 个字符，只能插入 i 个字符
    for (int i = 0; i <= b.size(); ++i) {
        dp[0][i] = i;
    }

    // 依次计算两个字符串的所有前缀之间的编辑距离
    for (int i = 1; i <= a.size(); i++) {
        for (int j = 1; j <= b.size(); j++) {
            // 保留当前字符，或在两个当前字符不同时修改当前字符
            int d1 = dp[i - 1][j - 1] + (a[i - 1] != b[j - 1]);

            // 在 A 的前 i 个字符末尾插入 B 的第 j 个字符
            int d2 = dp[i][j - 1] + 1;

            // 删除 A 的第 i 个字符
            int d3 = dp[i - 1][j] + 1;

            // 三种操作中取所需操作次数的最小值
            dp[i][j] = min(d1, min(d2, d3));
        }
    }

    // 输出完整字符串 A 转换为 B 所需的最少操作次数
    cout << dp[a.size()][b.size()] << endl;
    return 0;
}
